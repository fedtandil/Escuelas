CREATE OR REPLACE FUNCTION public.get_fed_school_administration(p_school_id TEXT)
RETURNS SETOF public.fed_school_administration
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT * FROM public.fed_school_administration
  WHERE school_id = p_school_id
    AND (public.is_fed() OR public.is_admin())
  ORDER BY cargo;
$$;

CREATE OR REPLACE FUNCTION public.save_fed_school_administration(
  p_school_id TEXT,
  p_cargo TEXT,
  p_nombre TEXT DEFAULT NULL,
  p_apellido TEXT DEFAULT NULL,
  p_tel TEXT DEFAULT NULL,
  p_dni TEXT DEFAULT NULL,
  p_cuil TEXT DEFAULT NULL,
  p_anotaciones TEXT DEFAULT NULL
)
RETURNS public.fed_school_administration
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  saved public.fed_school_administration;
BEGIN
  IF NOT (public.is_fed() OR public.is_admin()) THEN
    RAISE EXCEPTION 'Solo las cuentas F.E.D. o administradoras pueden guardar datos administrativos.';
  END IF;

  INSERT INTO public.fed_school_administration (
    school_id, cargo, nombre, apellido, tel, dni, cuil, anotaciones,
    created_by, created_at, updated_at
  )
  VALUES (
    p_school_id, p_cargo, p_nombre, p_apellido, p_tel, p_dni, p_cuil, p_anotaciones,
    auth.uid(), NOW(), NOW()
  )
  ON CONFLICT (school_id, cargo) DO UPDATE SET
    nombre = EXCLUDED.nombre,
    apellido = EXCLUDED.apellido,
    tel = EXCLUDED.tel,
    dni = EXCLUDED.dni,
    cuil = EXCLUDED.cuil,
    anotaciones = EXCLUDED.anotaciones,
    updated_at = NOW()
  RETURNING * INTO saved;

  RETURN saved;
END;
$$;

CREATE OR REPLACE FUNCTION public.set_fed_account_role(p_user_id UUID, p_role BOOLEAN)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Solo el administrador puede habilitar cuentas F.E.D.';
  END IF;

  UPDATE public.profiles
  SET role = COALESCE(p_role, FALSE), updated_at = NOW()
  WHERE id = p_user_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No existe el perfil solicitado.';
  END IF;
END;
$$;

