CREATE OR REPLACE FUNCTION public.is_fed()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid()
      AND role = TRUE
  );
$$;

CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (
    id, nombre, apellido, telefono, mail, contraseña, role, created_at, updated_at
  )
  VALUES (
    NEW.id,
    NULLIF(TRIM(COALESCE(NEW.raw_user_meta_data->>'nombre', '')), ''),
    NULLIF(TRIM(COALESCE(NEW.raw_user_meta_data->>'apellido', '')), ''),
    NULLIF(TRIM(COALESCE(NEW.raw_user_meta_data->>'telefono', '')), ''),
    NEW.email,
    COALESCE(NULLIF(NEW.raw_user_meta_data->>'contraseña', ''), NULLIF(NEW.raw_user_meta_data->>'password', '')),
    FALSE,
    NOW(),
    NOW()
  )
  ON CONFLICT (id) DO UPDATE SET
    nombre = COALESCE(EXCLUDED.nombre, public.profiles.nombre),
    apellido = COALESCE(EXCLUDED.apellido, public.profiles.apellido),
    telefono = COALESCE(EXCLUDED.telefono, public.profiles.telefono),
    mail = COALESCE(EXCLUDED.mail, public.profiles.mail),
    updated_at = NOW();

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_auth_user();

CREATE OR REPLACE FUNCTION public.set_review_author()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  NEW.user_id := auth.uid();
  SELECT TRIM(CONCAT(COALESCE(nombre, ''), ' ', COALESCE(apellido, '')))
  INTO NEW.author_name
  FROM public.profiles
  WHERE id = auth.uid();

  IF NEW.author_name IS NULL OR NEW.author_name = '' THEN
    NEW.author_name := COALESCE(auth.jwt()->>'email', 'Usuario');
  END IF;

  RETURN NEW;
END;
$$;

